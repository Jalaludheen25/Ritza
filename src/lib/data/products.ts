import type { Product, Badge, CategorySlug, CollectionSlug, Finish, Stone, TryOn } from "@/lib/types";

/* ------------------------------------------------------------------
   The catalogue. Authored through a small builder so each entry stays
   readable — the builder only fills defaults, every value below is
   written per piece.
------------------------------------------------------------------ */

type Draft = {
  id: string;
  slug: string;
  name: string;
  tagline: string;
  category: CategorySlug;
  collection: CollectionSlug;
  price: number;
  compareAt?: number;
  images: string[];
  description: string;
  detail: string;
  finish: Finish;
  stone: Stone;
  specs: [string, string][];
  badges?: Badge[];
  rating: number;
  reviewCount: number;
  inStock?: boolean;
  sizes?: string[];
  tryOn?: TryOn;
  pairsWith: string[];
};

const build = (d: Draft): Product => ({
  ...d,
  images: d.images.map((i) => `/images/${i}.jpg`),
  specs: d.specs.map(([label, value]) => ({ label, value })),
  badges: d.badges ?? [],
  inStock: d.inStock ?? true,
});

