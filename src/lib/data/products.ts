export const getProduct = (slug: string) => products.find((p) => p.slug === slug);

export const getProducts = (slugs: string[]) =>
  slugs.map((s) => products.find((p) => p.slug === s)).filter(Boolean) as Product[];

export const byCollection = (slug: string) => products.filter((p) => p.collection === slug);
export const byCategory = (slug: string) => products.filter((p) => p.category === slug);

export const byCollectionCategory = (collection: string, category: string) =>
  products.filter((p) => p.collection === collection && p.category === category);

export const newArrivals = products.filter((p) => p.badges.includes("new"));
export const bestSellers = products.filter((p) => p.badges.includes("bestseller"));
export const limited = products.filter((p) => p.badges.includes("limited"));

export const priceBounds = {
  min: Math.min(...products.map((p) => p.price)),
  max: Math.max(...products.map((p) => p.price)),
};

/** Simple content-based recommender: same category first, then same line. */
export function recommend(slug: string, limit = 4) {
  const product = getProduct(slug);
  if (!product) return products.slice(0, limit);
  const scored = products
    .filter((p) => p.slug !== slug)
    .map((p) => {
      let score = 0;
      if (p.category === product.category) score += 3;
      if (p.collection === product.collection) score += 2;
      if (p.finish === product.finish) score += 1;
      if (p.stone === product.stone && p.stone !== "None") score += 1;
      score -= Math.abs(p.price - product.price) / (priceBounds.max || 1);
      return { p, score };
    })
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.p);
}
